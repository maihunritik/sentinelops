CREATE TABLE incidents (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service          VARCHAR(64)  NOT NULL,
    type             VARCHAR(32)  NOT NULL,
    severity         VARCHAR(16)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    summary          VARCHAR(512) NOT NULL,
    opened_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at      TIMESTAMP WITH TIME ZONE,
    acknowledged_by  VARCHAR(64),
    note             VARCHAR(1024),
    peak_error_rate  DOUBLE PRECISION NOT NULL,
    peak_p95_ms      BIGINT NOT NULL,
    baseline_p95_ms  BIGINT,
    version          BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_incidents_status_opened ON incidents (status, opened_at DESC);
CREATE INDEX idx_incidents_service_type_status ON incidents (service, type, status);
